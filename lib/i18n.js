export function t(lang, key) {
  const dict = STRINGS[lang] || STRINGS.zh;
  return dict[key] !== undefined ? dict[key] : STRINGS.zh[key] || key;
}

// 有些地点数据字段是"中文字段 + 英文字段"这种并列写法（比如 description / descriptionEn），
// 这个小工具统一处理"英文模式下优先用xxxEn，没有就退回中文，绝不留空"的逻辑。
export function localizeField(place, fieldName, lang) {
  if (lang === "en") {
    const enField = place[`${fieldName}En`];
    if (enField !== undefined && enField !== null && enField !== "") return enField;
  }
  return place[fieldName];
}
